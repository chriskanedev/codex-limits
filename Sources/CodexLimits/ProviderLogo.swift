        let image = NSImage(size: NSSize(width: size, height: size), flipped: false) { rect in
            NSGraphicsContext.saveGraphicsState()
            defer { NSGraphicsContext.restoreGraphicsState() }
            NSGraphicsContext.current?.cgContext.translateBy(x: 0, y: rect.height)
            let dimension: CGFloat = provider == .codex ? 24 : 125
            NSGraphicsContext.current?.cgContext.scaleBy(x: rect.width / dimension, y: -rect.height / dimension)
            provider.nsColor.setFill()
            let path = provider == .codex ? codexPath() : claudePath()
            path.windingRule = .evenOdd
            path.fill()
            return true
        }
        image.isTemplate = false
        return image
    }

